"""Gate 6 sandbox tax-inclusive contract; locally signed fixtures only.

These HMACs are generated by the test author. They are NOT actual Stripe
deliveries, physical payment evidence, a tax calculation, or a release gate.
"""
import json
import os
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

import cloud_webhook
import sandbox_gate6_preflight as preflight
from test_webhook_crypto import BASE, checkout, event, invoice, signed


class SandboxTaxInclusiveContractTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.env = patch.dict(os.environ, {
            "DATABASE_PATH": str(Path(self.tmp.name) / "isolated.sqlite3"),
            "STRIPE_WEBHOOK_SECRET": "whsec_local_gate6_unit_test",
            "STRIPE_EXPECT_LIVEMODE": "false",
            "RACE_PAYMENT_LINK_ID": "plink_local_gate6_test",
            "RACE_PRICE_ID": preflight.SANDBOX_PRICE_ID,
        })
        self.env.start()
        self.client = cloud_webhook.app.test_client()

    def tearDown(self):
        self.env.stop()
        self.tmp.cleanup()

    def send(self, evt):
        raw = json.dumps(evt, sort_keys=True, separators=(",", ":")).encode()
        return self.client.post(
            "/webhook", data=raw, content_type="application/json",
            headers={"Stripe-Signature": signed(
                raw, secret="whsec_local_gate6_unit_test")})

    def checkout(self, amount=2900, livemode=False):
        data = dict(checkout())
        data["payment_link"] = "plink_local_gate6_test"
        data["amount_total"] = amount
        data["total_details"] = {"amount_tax": 400}  # Synthetic, not a measured rate.
        return event("checkout.session.completed", data,
                     created=BASE + 20, livemode=livemode)

    def paid_invoice(self, amount=2900, price_id=None):
        data = invoice()
        data["total"] = amount
        data["amount_paid"] = amount
        data["total_taxes"] = [{"amount": 400}]  # Synthetic tax-inclusive split.
        data["lines"]["data"][0]["pricing"]["price_details"]["price"] = (
            price_id or preflight.SANDBOX_PRICE_ID)
        return event("invoice.paid", data, created=BASE + 21)

    def active(self):
        return cloud_webhook.store.is_active("sub_signed_123", BASE + 22)

    def test_inclusive_gross_2900_may_grant_only_with_signed_checkout_and_invoice(self):
        checkout_response = self.send(self.checkout())
        self.assertEqual(checkout_response.status_code, 200)
        self.assertTrue(checkout_response.json["handled"])
        self.assertFalse(self.active())
        paid_response = self.send(self.paid_invoice())
        self.assertEqual(paid_response.status_code, 200)
        self.assertTrue(paid_response.json["handled"])
        self.assertTrue(self.active())

    def test_exclusive_like_tax_added_to_2900_is_rejected(self):
        self.send(self.checkout(amount=3300))
        self.send(self.paid_invoice(amount=3300))
        self.assertFalse(self.active())

    def test_invalid_signed_price_cannot_grant(self):
        self.send(self.checkout())
        response = self.send(self.paid_invoice(
            price_id="price_1UQdzi5TQIzi9HKPizM62pvD"))
        self.assertEqual(response.status_code, 200)
        self.assertFalse(response.json["handled"])
        self.assertFalse(self.active())

    def test_signed_live_event_rejected_by_sandbox(self):
        response = self.send(self.checkout(livemode=True))
        self.assertEqual(response.status_code, 400)
        self.assertEqual(response.json["error"], "wrong_stripe_mode")
        self.assertFalse(self.active())

    def test_missing_tax_blocked_payment_link_fails_closed(self):
        with patch.dict(os.environ, {"RACE_PAYMENT_LINK_ID": ""}):
            response = self.send(self.checkout())
        self.assertEqual(response.status_code, 503)
        self.assertFalse(self.active())

    def test_actual_sandbox_config_is_not_misrepresented_as_proven(self):
        blank = preflight.examine({
            "STRIPE_EXPECT_LIVEMODE": "false",
            "RACE_PRICE_ID": preflight.SANDBOX_PRICE_ID,
            "RACE_PAYMENT_LINK_ID": "",
            "STRIPE_WEBHOOK_SECRET": "",
            "DATABASE_PATH": "",
        })
        self.assertEqual(blank["result"], "BLOCKED")
        self.assertIn("SANDBOX_PAYMENT_LINK_MISSING", blank["blockers"])
        self.assertIn("WEBHOOK_SIGNING_SECRET_MISSING", blank["blockers"])
        self.assertIn("ABSOLUTE_STORAGE_PATH_MISSING", blank["blockers"])
        self.assertEqual(blank["production_authority"], "NONE")

    def test_even_complete_local_config_is_not_stripe_delivery_proof(self):
        result = preflight.examine({
            "STRIPE_EXPECT_LIVEMODE": "false",
            "RACE_PRICE_ID": preflight.SANDBOX_PRICE_ID,
            "RACE_PAYMENT_LINK_ID": "plink_local_mock",
            "STRIPE_WEBHOOK_SECRET": "whsec_local_mock",
            "DATABASE_PATH": str(Path(self.tmp.name) / "mock.sqlite3"),
        })
        self.assertEqual(result["blockers"], [])
        self.assertEqual(result["result"], "LOCAL_CONFIG_ONLY_NOT_EXTERNAL_VERIFIED")
        self.assertIn("STRIPE_TAX_HEAD_OFFICE_AND_REGISTRATION",
                      result["unverified_external_requirements"])

    def test_live_mode_cannot_pass_sandbox_preflight(self):
        env = {
            "STRIPE_EXPECT_LIVEMODE": "true",
            "RACE_PRICE_ID": preflight.SANDBOX_PRICE_ID,
            "RACE_PAYMENT_LINK_ID": "plink_local_mock",
            "STRIPE_WEBHOOK_SECRET": "whsec_local_mock",
            "DATABASE_PATH": str(Path(self.tmp.name) / "mock.sqlite3"),
        }
        result = preflight.examine(env)
        self.assertEqual(result["result"], "BLOCKED")
        self.assertIn("SANDBOX_MODE_REQUIRED", result["blockers"])

    def test_template_leaves_unverified_values_empty(self):
        raw = (Path(__file__).resolve().parents[1] /
               ".env.sandbox.example").read_text(encoding="utf-8")
        self.assertIn("RACE_PRICE_ID=" + preflight.SANDBOX_PRICE_ID, raw)
        self.assertIn("STRIPE_EXPECT_LIVEMODE=false", raw)
        self.assertIn("\nRACE_PAYMENT_LINK_ID=\n", raw)
        self.assertIn("\nSTRIPE_WEBHOOK_SECRET=\n", raw)
        self.assertIn("\nDATABASE_PATH=\n", raw)
        self.assertNotIn("sk_live_", raw)


if __name__ == "__main__":
    unittest.main()
